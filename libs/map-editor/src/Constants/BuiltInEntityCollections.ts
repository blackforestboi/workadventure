export function isBuiltInEntityPrefabReference(reference: { collectionName: string; id: string }): boolean {
    return BUILT_IN_ENTITY_COLLECTIONS.some(
        (collection) =>
            collection.collectionName === reference.collectionName &&
            (collection.prefabIds as readonly string[]).includes(reference.id),
    );
}

export function isBuiltInEntityCollectionUrl(url: URL): boolean {
    return BUILT_IN_ENTITY_COLLECTIONS.some((collection) => collection.urlPath === url.pathname);
}
